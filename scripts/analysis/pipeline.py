# Prompt for a fundamental-analysis run on an ETF or mutual fund.
FUND_PROMPT = "fundamental_etf"


def save_analysis_report(ticker: str, content: str, output_dir: Path,
                         analysis_type: str, provider: str = "claude",
                         model: str = "", extra_fields: "dict | None" = None) -> Path:
    """Save report with YAML frontmatter and same-day deduplication.

    ``extra_fields`` are appended to the front matter after the standard ones
    (provenance and checks recorded by :func:`run_analysis`).
    """
    output_dir = Path(output_dir)
    meta = ANALYSIS_TYPES[analysis_type]
    prefix = meta["filename_prefix"]
    label = meta["label"]
    ext = meta.get("ext", ".md")

    base = f"{prefix}_{TODAY}_{provider}"  # provider: "openai" | "claude" | "gemini"
    path = dedup_path(output_dir, base, ext)

    if ext == ".html":
        path.write_text(content, encoding="utf-8")
    else:
        # Repair LLM-emitted Mermaid syntax (unquoted parens/colons in node
        # labels, etc.) so the source .md GitHub renders directly is valid,
        # not only the docs-site copy. Only ```mermaid fences are touched, so
        # any embedded chart HTML is left byte-for-byte intact. Idempotent, so
        # build_docs re-running it later is a no-op.
        content = sanitize_mermaid_blocks(content)
        generated_by = _GENERATED_BY.get(provider, "Claude AI")
        fm = frontmatter({
            "title": f'"{ticker} {label} {TODAY}"',
            "date": TODAY,
            "ticker": ticker,
            "analysis_type": analysis_type,
            "provider": provider,
            "model": model,
            "language": "zh-TW",
            "generated_by": f"{generated_by} (scripts/generate_analysis.py)",
            **(extra_fields or {}),
        })
        path.write_text(fm + content, encoding="utf-8")

    print(f"  ✅ saved → {path}")
    return path


def run_analysis(ticker: str, analysis_type: str, provider: str | None,
                 model: str | None, max_tokens: int, output_dir: Path) -> Path:
    """Fetch data, build context, generate the report, and save it. Returns path.

    ``provider`` / ``model`` are the primary override (either may be ``None``);
    the report is generated by trying the resolved provider fallback chain and
    keeping the first success — so the data/context are fetched only once and
    reused across fallback attempts. The provider that actually produced the
    report is recorded in the saved frontmatter.
    """
    output_dir = Path(output_dir)
    attempts = resolve_chain(provider, model, analysis_type)

    print("[1/3] Fetching financial data from Yahoo Finance …")
    data = fetch_data(ticker)
    if analysis_type == "technical-analysis":
        require_price_history(ticker, data)
        # The same longer history the context reads, so the levels recorded
        # here are the levels the model was shown.
        data["technical_levels"] = key_levels(
            data["hist"], long_history(prices.report_key(ticker)))
    prompt_file = None
    if analysis_type == "fundamental-analysis":
        inputs = report_inputs.gather(ticker, data.get("info"))
        report_inputs.prefer_newer_close(data, inputs["bars"])
        data["source_status"] = {**data.get("source_status", {}), **inputs["status"]}
        data["report_facts"] = compute_facts(data, inputs)
        if data["report_facts"]["is_fund"]:
            # A fund is not a company: its own figures, context and prompt.
            profile = report_inputs.fund_profile(ticker, data.get("info"))
            data["source_status"]["fund_profile"] = bool(profile)
            data["fund_facts"] = fund_facts.gather(data, profile)
            prompt_file = FUND_PROMPT
    context = build_context(data, analysis_type)

    print(f"[2/3] Generating report (chain: {' → '.join(p for p, _ in attempts)}) …")
    report, used_provider, used_model = run_with_fallback(
        attempts,
        lambda p, m: call_llm(ticker, context, analysis_type, p, m, max_tokens,
                              **({"prompt_file": prompt_file} if prompt_file else {})),
    )

    extra = provenance(data, analysis_type, used_provider, max_tokens, used_model, prompt_file)
    if analysis_type == "fundamental-analysis":
        report = stamp_sources(report, data.get("source_status") or {})
        if not prompt_file:           # a fund report has no §8.8 to recheck
            report, checks = recheck_valuation(report, data.get("report_facts") or {})
            extra.update(checks)
            report, card = scorecard.fix(report, scorecard.FUNDAMENTAL)
            extra.update(verdict(report, card, data.get("report_facts") or {}, checks))
    elif analysis_type == "technical-analysis":
        report, card = scorecard.fix(report, scorecard.TECHNICAL)
        extra.update(score_fields(card))
        if card["total"] is not None:
            extra["signal"] = scorecard.signal(card["total"])
            was = scorecard.signal(card["stated"]) if card.get("corrected") else None
            if was and was != extra["signal"]:
                # The strategy chapter was routed on the score the model
                # printed. The composite is corrected; the prose is not, so the
                # disagreement is recorded, shown to the reader and left for
                # stage-1 QA to flag (SIGNAL_CHANGED).
                extra["signal_stated"] = was
                data["signal_change"] = {"from": was, "to": extra["signal"],
                                         "stated": card["stated"], "score": card["total"]}
                print(f"  ⚠ corrected composite moves the signal {was} → {extra['signal']}; "
                      "chapter 8 was written for the stated score")
    report, repaired = derivation.fix(report)
    if repaired:
        extra["derivation_fixed"] = repaired
        print(f"  ✏ repaired {repaired} number(s) in a displayed equation chain")

    if analysis_type in SOURCED_TYPES:
        report = report.rstrip() + "\n" + data_sources_block(
            data, analysis_type, used_provider, used_model)

    print(f"[3/3] Saving report (generated by {used_provider}) …")
    return save_analysis_report(ticker, report, output_dir,
                                analysis_type, provider=used_provider, model=used_model,
                                extra_fields=extra)


def require_price_history(ticker: str, data: dict) -> None:
    """Refuse to write a technical report without bars or a price.

    A technical report is nothing but its price data. Without it the model
    wrote one anyway: every 0050 report in October was "modelled" at ~$195
    (actual NT$108) from an empty history, and eight 2026-10-23 reports were
    built on a ``$nan`` close. A failed run publishes nothing, which is better.
    """
    hist = data.get("hist")
    if hist is None or hist.empty or data.get("price_now") is None:
        raise DataFetchError(f"{ticker}: no daily price history or close — "
                             "not generating a technical report from nothing")


# Display names for source_status keys, in header order. Keys that are inputs
# to another source (price_store, peers, risk_free_rate) are not listed.
_SOURCE_NAMES = (
    (("sec_live", "fundamentals_store"), "SEC 申報資料 (XBRL)"),
    (("yfinance_info", "yfinance_prices", "yfinance_statements"), "Yahoo Finance"),
    (("finviz",), "Finviz"),
    (("stockanalysis",), "StockAnalysis"),
    (("roic",), "Roic.ai"),
)


def provenance(data: dict, analysis_type: str, provider: str, max_tokens: int,
               model: str = "", prompt_file: "str | None" = None) -> dict:
    """Front-matter fields that say how a report was produced: the prompt
    version, sampling parameters, the price it was given and which data
    sources actually answered."""
    fields = {
        "prompt_sha256": (prompt_fingerprint(analysis_type, provider, prompt_file) if prompt_file
                          else prompt_fingerprint(analysis_type, provider)),
        "temperature": REPORT_TEMPERATURE,
        "max_tokens": max_tokens,
    }
    if not accepts_temperature(provider, model):
        # Claude and the OpenAI reasoning models sample at their own default;
        # recording 0.3 would claim a setting the request never carried.
        del fields["temperature"]
    if data.get("fund_facts"):
        # Stage-1 QA checks a fund report against the fund chapters, not 1–11.
        fields["instrument"] = "fund"
    if data.get("price_now") is not None:
        fields["price"] = round(float(data["price_now"]), 4)
        fields["price_date"] = data.get("price_date") or "unknown"
    if data.get("close_source"):
        fields["close_source"] = data["close_source"]
    if analysis_type == "technical-analysis" and data.get("technical_levels"):
        fields["levels"] = f'"{levels_summary(data["technical_levels"])}"'
    v = (data.get("report_facts") or {}).get("valuation") if analysis_type == "fundamental-analysis" else None
    if v and v.get("methods"):
        # What Python computed, for stage-1 QA to compare the report against.
        fields["valuation"] = f'"{valuation.summary(v)}"'
        fields["fair_value_computed"] = v["fair_value"]
        fields["rating_computed"] = v["rating"]
    if v and v["dcf"].get("available"):
        fields["dcf_value"] = round(v["dcf"]["value"], 2)
    status = data.get("source_status") or {}
    if status:
        fields["data_sources_ok"] = ", ".join(k for k, v in status.items() if v) or "none"
        fields["data_sources_failed"] = ", ".join(k for k, v in status.items() if not v) or "none"
    return fields


def stamp_sources(report: str, status: dict) -> str:
    """Replace the header's 數據來源 with the sources that returned data.

    The prompt's header used to claim "Yahoo Finance, Finviz, StockAnalysis,
    Roic.ai" whether or not those scrapers had answered.
    """
    if not status:
        return report
    names = [name for keys, name in _SOURCE_NAMES if any(status.get(k) for k in keys)]
    if not names:
        return report
    return re.sub(r"(\*\*數據來源\*\*：)[^｜\n]*", lambda m: m.group(1) + "、".join(names) + " ",
                  report, count=1)


def score_fields(card: dict) -> dict:
    """``score`` (the composite Python computed from the scorecard's
    sub-scores) and, when the report printed a different one, ``score_stated``.
    Empty when the scorecard could not be read in full."""
    if card.get("total") is None:
        return {}
    fields = {"score": card["total"]}
    if card.get("corrected"):
        fields["score_stated"] = card["stated"]
        print(f"  ✏ scorecard composite {card['stated']} → {card['total']} (mean of its sub-scores)")
    return fields


def verdict(report: str, card: dict, facts: dict, checks: dict) -> dict:
    """A fundamental report's machine-readable verdict: ``rating``, ``score``
    and ``fair_value``.

    ``rating`` is the one the report states — rule 20 lets it move one notch
    from the computed rating, with its reason — and falls back to the computed
    one. ``fair_value`` is the report's weighted fair value once it rechecks
    (ok or corrected), else what Python computed.
    """
    v = facts.get("valuation") or {}
    fields = score_fields(card)
    rating = scorecard.stated_rating(report) or v.get("rating")
    if rating:
        fields["rating"] = rating
    fair = (checks.get("weighted_fair_value_recomputed")
            if checks.get("arithmetic_check") in ("ok", "corrected") else None) or v.get("fair_value")
    if fair:
        fields["fair_value"] = fair
    return fields


# Report types that end with a 資料與來源 block.
SOURCED_TYPES = ("fundamental-analysis", "technical-analysis")
_CLOSE_SOURCES = {"daily_bar": "Yahoo Finance 日線", "quote": "Yahoo Finance 即時報價（該交易日已收盤）",
                  "price_store": "價格資料庫（data/prices）"}
SOURCES_HEADING = "## 資料與來源"


def data_sources_block(data: dict, analysis_type: str, provider: str, model: str = "") -> str:
    """The closing 資料與來源 table, written by the pipeline from what it
    recorded — not by the model, which used to cite "資料包" or "題示".

    It says which close the report was built on, which filing the statements
    come from, which sources answered and which did not, and which figures
    were computed in Python rather than estimated.
    """
    info = data.get("info") or {}
    facts = data.get("report_facts") or {}
    status = data.get("source_status") or {}
    rows = []
    if data.get("price_now") is not None:
        source = _CLOSE_SOURCES.get(data.get("close_source"), "Yahoo Finance")
        rows.append(("價格", f"{float(data['price_now']):,.2f} {info.get('currency') or ''}".strip()
                     + f"，{data.get('price_date') or '日期不明'} 收盤（{source}）"))
    if analysis_type == "fundamental-analysis":
        stmt = facts.get("statements")
        if data.get("fund_facts"):
            rows.append(("基金資料", "Yahoo Finance（持股、費用率、規模）；績效與回撤由價格資料庫計算"))
        elif stmt:
            period = f"，最新季度 {stmt['period_end']}（{stmt['fiscal_label']}）" if stmt.get("period_end") else ""
            rows.append(("財務報表", f"{stmt['source']}{period}"))
        computed = ("基金的集中度、績效、費用與回撤試算" if data.get("fund_facts") else
                    "TTM 數字、WACC、DCF 模型、估值方法與權重、加權合理價值、MOS、評級門檻、"
                    "F-Score、杜邦分解、營運資金天數、綜合評分")
    else:
        hist = complete(data.get("hist"))
        if hist is not None and not hist.empty:
            rows.append(("K 棒", f"{len(hist)} 根日線，{str(hist.index[0])[:10]} 至 {str(hist.index[-1])[:10]}"
                                 "（Yahoo Finance）；較長期間的價位與基準機率取自價格資料庫"))
        look = (data.get("technical_levels") or {}).get("lookback") or {}
        if look:
            name = lambda n: LEVEL_LOOKBACK_NAMES.get(n, f"近 {n} 個交易日")
            rows.append(("關鍵價位回溯期間", f"阻力 {name(look['resistance'])}、支撐 {name(look['support'])}"))
        if data.get("earnings_date"):
            rows.append(("下次財報日", f"{data['earnings_date']}（Yahoo Finance，日期可能調整）"))
        computed = "所有指標、R1–S3 與斐波那契價位、多時框方向、相對強度、缺口、歷史基準機率、綜合評分"
        change = data.get("signal_change")
        if change:
            names = {"bullish": "偏多", "neutral": "中性", "bearish": "偏空"}
            rows.append(("⚠️ 評分覆核", f"模型寫的綜合評分為 {change['stated']:g}（{names[change['from']]}），"
                                        f"依六項子評分重算為 {change['score']}（{names[change['to']]}）。"
                                        "第 8 章的策略方向是依原評分撰寫，與重算後的評分區間不一致，請以此為前提閱讀"))
    answered = [name for keys, name in _SOURCE_NAMES if any(status.get(k) for k in keys)]
    silent = [name for keys, name in _SOURCE_NAMES
              if any(k in status for k in keys) and not any(status.get(k) for k in keys)]
    if answered:
        rows.append(("有回應的資料來源", "、".join(answered)))
    if silent:
        rows.append(("未回應的資料來源", "、".join(silent)))
    rows.append(("由程式計算", computed))
    rows.append(("撰寫模型", " / ".join(x for x in (provider, model) if x)))
    table = "\n".join(f"| {k} | {v} |" for k, v in rows)
    return (f"\n---\n\n{SOURCES_HEADING}\n\n| 項目 | 內容 |\n|------|------|\n{table}\n\n"
            "> 本區塊由產生報告的程式依實際取得的資料填寫，非模型撰寫。「由程式計算」的數字不是模型的估計；"
            "其餘判斷（評分、情境、策略）是模型的分析。\n")


def recheck_valuation(report: str, facts: dict) -> "tuple[str, dict]":
    """Recompute §8.8 from the report's own terms, correct and annotate.

    A mis-added total whose weights sum to 100% is replaced by the sum of its
    terms throughout the report (``arithmetic_check: corrected``); the model's
    original stays in ``weighted_fair_value_stated`` and in the notice.

    MOS and upside use the price the context handed the model, so a report
    that quoted a different price is corrected too. Returns the annotated
    report and the front-matter fields recording the check.
    """
    result = arithmetic.check(report, price=facts.get("price"))
    fields = {"arithmetic_check": result["status"]}
    if result["status"] != "unparsed":
        fields["weighted_fair_value_stated"] = result["stated"]
        fields["weighted_fair_value_recomputed"] = result["total"]
        if result["mos"] is not None:
            fields["mos_recomputed_pct"] = result["mos"]
    if result["status"] == "mismatch":
        corrected = arithmetic.correct(report, result)
        # Only a rewrite that now rechecks clean counts: a total printed in a
        # form correct() does not match ("$334.3") would leave MOS rewritten
        # around a total that still disagrees with its terms.
        if (corrected != report and
                arithmetic.check(corrected, price=facts.get("price"))["status"] == "ok"):
            report, result = corrected, {**result, "status": "corrected"}
            fields["arithmetic_check"] = "corrected"
        print(f"  ⚠ §8.8 weighted fair value {result['stated']} ≠ Σ terms "
              f"{result['total']} ({result['diff_pct']:+.2f}%) — {result['status']}")
    # Before annotate(), whose recap line is correct by construction.
    report = arithmetic.fix_products(report, result)
    return arithmetic.annotate(report, result), fields


