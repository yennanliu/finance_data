"""Run layer: orchestrate a single analysis report end-to-end.

fetch (data) → assemble (context) → generate (llm) → publish.
This is importable so an analysis can be produced programmatically; the
``generate_analysis.py`` CLI is a thin wrapper over :func:`run_analysis`.

Reports carry no chart markup. Technical report *pages* render the shared k-line
widget, injected by ``scripts/build_docs.py`` from the committed price store —
so the chart is no longer baked into the report at generation time. See
``docs/PRICE_STORE_DESIGN.md``.
"""

from __future__ import annotations

from pathlib import Path

import re

from .config import ANALYSIS_TYPES, REPORT_TEMPERATURE, TODAY
from .config.providers import resolve_chain
from .context import build_context
from .context.fundamental_facts import compute_facts
from .data import report_inputs
from .data.sources import fetch_data
from .data.technicals import key_levels, levels_summary
from .exceptions import DataFetchError
from .llm import call_llm, prompt_fingerprint, run_with_fallback
from .publish import GENERATED_BY as _GENERATED_BY, dedup_path, frontmatter
from .utils.mermaid import sanitize_mermaid_blocks
from .validate import arithmetic, derivation


def save_analysis_report(ticker: str, content: str, output_dir: Path,
                         analysis_type: str, provider: str = "claude",
                         model: str = "", extra_fields: "dict | None" = None) -> Path:
    """Save report with YAML frontmatter and same-day deduplication.

    ``extra_fields`` are appended to the front matter after the standard ones
    (provenance and checks recorded by :func:`run_analysis`).
    """
    output_dir = Path(output_dir)
    meta = ANALYSIS_TYPES[analysis_type]
    prefix = meta["filename_prefix"]
    label = meta["label"]
    ext = meta.get("ext", ".md")

    base = f"{prefix}_{TODAY}_{provider}"  # provider: "openai" | "claude" | "gemini"
    path = dedup_path(output_dir, base, ext)

    if ext == ".html":
        path.write_text(content, encoding="utf-8")
    else:
        # Repair LLM-emitted Mermaid syntax (unquoted parens/colons in node
        # labels, etc.) so the source .md GitHub renders directly is valid,
        # not only the docs-site copy. Only ```mermaid fences are touched, so
        # any embedded chart HTML is left byte-for-byte intact. Idempotent, so
        # build_docs re-running it later is a no-op.
        content = sanitize_mermaid_blocks(content)
        generated_by = _GENERATED_BY.get(provider, "Claude AI")
        fm = frontmatter({
            "title": f'"{ticker} {label} {TODAY}"',
            "date": TODAY,
            "ticker": ticker,
            "analysis_type": analysis_type,
            "provider": provider,
            "model": model,
            "language": "zh-TW",
            "generated_by": f"{generated_by} (scripts/generate_analysis.py)",
            **(extra_fields or {}),
        })
        path.write_text(fm + content, encoding="utf-8")

    print(f"  ✅ saved → {path}")
    return path


def run_analysis(ticker: str, analysis_type: str, provider: str | None,
                 model: str | None, max_tokens: int, output_dir: Path) -> Path:
    """Fetch data, build context, generate the report, and save it. Returns path.

    ``provider`` / ``model`` are the primary override (either may be ``None``);
    the report is generated by trying the resolved provider fallback chain and
    keeping the first success — so the data/context are fetched only once and
    reused across fallback attempts. The provider that actually produced the
    report is recorded in the saved frontmatter.
    """
    output_dir = Path(output_dir)
    attempts = resolve_chain(provider, model)

    print("[1/3] Fetching financial data from Yahoo Finance …")
    data = fetch_data(ticker)
    if analysis_type == "technical-analysis":
        require_price_history(ticker, data)
        data["technical_levels"] = key_levels(data["hist"])
    if analysis_type == "fundamental-analysis":
        inputs = report_inputs.gather(ticker, data.get("info"))
        report_inputs.prefer_newer_close(data, inputs["bars"])
        data["source_status"] = {**data.get("source_status", {}), **inputs["status"]}
        data["report_facts"] = compute_facts(data, inputs)
    context = build_context(data, analysis_type)

    print(f"[2/3] Generating report (chain: {' → '.join(p for p, _ in attempts)}) …")
    report, used_provider, used_model = run_with_fallback(
        attempts,
        lambda p, m: call_llm(ticker, context, analysis_type, p, m, max_tokens),
    )

    extra = provenance(data, analysis_type, used_provider, max_tokens)
    if analysis_type == "fundamental-analysis":
        report = stamp_sources(report, data.get("source_status") or {})
        report, checks = recheck_valuation(report, data.get("report_facts") or {})
        extra.update(checks)
    report, repaired = derivation.fix(report)
    if repaired:
        extra["derivation_fixed"] = repaired
        print(f"  ✏ repaired {repaired} number(s) in a displayed equation chain")

    print(f"[3/3] Saving report (generated by {used_provider}) …")
    return save_analysis_report(ticker, report, output_dir,
                                analysis_type, provider=used_provider, model=used_model,
                                extra_fields=extra)


def require_price_history(ticker: str, data: dict) -> None:
    """Refuse to write a technical report without bars or a price.

    A technical report is nothing but its price data. Without it the model
    wrote one anyway: every 0050 report in October was "modelled" at ~$195
    (actual NT$108) from an empty history, and eight 2026-10-23 reports were
    built on a ``$nan`` close. A failed run publishes nothing, which is better.
    """
    hist = data.get("hist")
    if hist is None or hist.empty or data.get("price_now") is None:
        raise DataFetchError(f"{ticker}: no daily price history or close — "
                             "not generating a technical report from nothing")


# Display names for source_status keys, in header order. Keys that are inputs
# to another source (price_store, peers, risk_free_rate) are not listed.
_SOURCE_NAMES = (
    (("sec_live", "fundamentals_store"), "SEC 申報資料 (XBRL)"),
    (("yfinance_info", "yfinance_prices", "yfinance_statements"), "Yahoo Finance"),
    (("finviz",), "Finviz"),
    (("stockanalysis",), "StockAnalysis"),
    (("roic",), "Roic.ai"),
)


def provenance(data: dict, analysis_type: str, provider: str, max_tokens: int) -> dict:
    """Front-matter fields that say how a report was produced: the prompt
    version, sampling parameters, the price it was given and which data
    sources actually answered."""
    fields = {
        "prompt_sha256": prompt_fingerprint(analysis_type, provider),
        "temperature": REPORT_TEMPERATURE,
        "max_tokens": max_tokens,
    }
    if data.get("price_now") is not None:
        fields["price"] = round(float(data["price_now"]), 4)
        fields["price_date"] = data.get("price_date") or "unknown"
    if data.get("close_source"):
        fields["close_source"] = data["close_source"]
    if analysis_type == "technical-analysis" and data.get("technical_levels"):
        fields["levels"] = f'"{levels_summary(data["technical_levels"])}"'
    status = data.get("source_status") or {}
    if status:
        fields["data_sources_ok"] = ", ".join(k for k, v in status.items() if v) or "none"
        fields["data_sources_failed"] = ", ".join(k for k, v in status.items() if not v) or "none"
    return fields


def stamp_sources(report: str, status: dict) -> str:
    """Replace the header's 數據來源 with the sources that returned data.

    The prompt's header used to claim "Yahoo Finance, Finviz, StockAnalysis,
    Roic.ai" whether or not those scrapers had answered.
    """
    if not status:
        return report
    names = [name for keys, name in _SOURCE_NAMES if any(status.get(k) for k in keys)]
    if not names:
        return report
    return re.sub(r"(\*\*數據來源\*\*：)[^｜\n]*", lambda m: m.group(1) + "、".join(names) + " ",
                  report, count=1)


def recheck_valuation(report: str, facts: dict) -> "tuple[str, dict]":
    """Recompute §8.8 from the report's own terms, correct and annotate.

    A mis-added total whose weights sum to 100% is replaced by the sum of its
    terms throughout the report (``arithmetic_check: corrected``); the model's
    original stays in ``weighted_fair_value_stated`` and in the notice.

    MOS and upside use the price the context handed the model, so a report
    that quoted a different price is corrected too. Returns the annotated
    report and the front-matter fields recording the check.
    """
    result = arithmetic.check(report, price=facts.get("price"))
    fields = {"arithmetic_check": result["status"]}
    if result["status"] != "unparsed":
        fields["weighted_fair_value_stated"] = result["stated"]
        fields["weighted_fair_value_recomputed"] = result["total"]
        if result["mos"] is not None:
            fields["mos_recomputed_pct"] = result["mos"]
    if result["status"] == "mismatch":
        corrected = arithmetic.correct(report, result)
        # Only a rewrite that now rechecks clean counts: a total printed in a
        # form correct() does not match ("$334.3") would leave MOS rewritten
        # around a total that still disagrees with its terms.
        if (corrected != report and
                arithmetic.check(corrected, price=facts.get("price"))["status"] == "ok"):
            report, result = corrected, {**result, "status": "corrected"}
            fields["arithmetic_check"] = "corrected"
        print(f"  ⚠ §8.8 weighted fair value {result['stated']} ≠ Σ terms "
              f"{result['total']} ({result['diff_pct']:+.2f}%) — {result['status']}")
    # Before annotate(), whose recap line is correct by construction.
    report = arithmetic.fix_products(report, result)
    return arithmetic.annotate(report, result), fields


