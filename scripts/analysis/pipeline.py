"""Run layer: orchestrate a single analysis report end-to-end.

fetch (data) → assemble (context) → generate (llm) → publish.
This is importable so an analysis can be produced programmatically; the
``generate_analysis.py`` CLI is a thin wrapper over :func:`run_analysis`.

Reports carry no chart markup. Technical report *pages* render the shared k-line
widget, injected by ``scripts/build_docs.py`` from the committed price store —
so the chart is no longer baked into the report at generation time. See
``docs/PRICE_STORE_DESIGN.md``.
"""

from __future__ import annotations

from pathlib import Path

import re

from .config import ANALYSIS_TYPES, REPORT_TEMPERATURE, TODAY
from .config.providers import resolve_chain
from .context import build_context
from .context import fund_facts, valuation
from .context.fundamental_facts import compute_facts
from .data import prices, report_inputs
from .data.sources import fetch_data
from .data.technicals import LEVEL_LOOKBACK_NAMES, complete, key_levels, levels_summary, long_history
from .exceptions import DataFetchError
